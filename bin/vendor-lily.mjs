#!/usr/bin/env node
// Vendor the Lily Design System pieces this site uses, so the site builds
// standalone with no dependency on a local Lily checkout or an npm release.
//
// Source: $LILY if set, else ../../lilydesignsystem/lily-design-system.
// Run after Lily changes:  npm run sync:lily
//
// Three things are copied:
//   1. headless components -> src/lib/lily/          (unstyled markup + a11y)
//   2. helper pickers      -> src/lib/lily-helpers/  (theme + text size)
//   3. themes              -> static/assets/themes/  (the stylesheets a picker swaps)

import { copyFile, mkdir, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const siteRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const lily = resolve(
	process.env.LILY ?? join(siteRoot, '..', '..', 'lilydesignsystem', 'lily-design-system')
);

if (!existsSync(join(lily, 'themes'))) {
	console.error(`No Lily checkout found at ${lily}. Set LILY=/path/to/lily-design-system.`);
	process.exit(1);
}

// Headless components used by this site. Each is copied from
// lily-design-system-svelte-headless/components/<Name>/<Name>.svelte.
const components = [
	'ArticleLayout',
	'Badge',
	'BreadcrumbList',
	'BreadcrumbListItem',
	'BreadcrumbNav',
	'Card',
	'ContentsList',
	'ContentsListItem',
	'ContentsNav',
	'Footer',
	'Header',
	'PaginationList',
	'PaginationListItem',
	'PaginationNav',
	'SearchInput',
	'SectionHeading',
	'SectionList',
	'SectionListItem',
	'SectionNav',
	'SkipLink'
];

// Helper components: standalone packages, each one <Name>.svelte at its root.
const helpers = [
	['lily-design-system-svelte-theme-picker', 'ThemePicker'],
	['lily-design-system-svelte-text-size-picker', 'TextSizePicker']
];

// Themes offered by the theme picker. Curated rather than exhaustive: the
// neutral reading themes, plus the government and national-health-service
// themes that match the institutions this book is written for.
const themes = [
	'light',
	'dark',
	'dim',
	'night',
	'winter',
	'nord',
	'silk',
	'corporate',
	'business',
	'lofi',
	'retro',
	'sunset',
	'united-kingdom-government-digital-service',
	'united-kingdom-national-health-service-england-for-patients',
	'united-kingdom-national-health-service-england-for-practitioners',
	'united-kingdom-national-health-service-scotland-for-patients',
	'united-kingdom-national-health-service-scotland-for-practitioners',
	'united-kingdom-national-health-service-wales-for-patients',
	'united-kingdom-national-health-service-wales-for-practitioners',
	'united-states-web-design-system'
];

const headlessSrc = join(lily, 'lily-design-system-svelte-headless', 'components');
const helpersSrc = join(lily, 'lily-design-system-svelte-helpers');
const themesSrc = join(lily, 'themes');

const componentsOut = join(siteRoot, 'src', 'lib', 'lily');
const helpersOut = join(siteRoot, 'src', 'lib', 'lily-helpers');
const themesOut = join(siteRoot, 'static', 'assets', 'themes');

for (const dir of [componentsOut, helpersOut, themesOut]) {
	await rm(dir, { recursive: true, force: true });
	await mkdir(dir, { recursive: true });
}

const banner = (from) =>
	`<!-- Vendored from Lily Design System: ${from}\n` +
	`     Do not edit here. Edit upstream, then: npm run sync:lily -->\n`;

let count = 0;
const missing = [];

async function vendorSvelte(from, to, label) {
	if (!existsSync(from)) {
		missing.push(label);
		return;
	}
	const { readFile } = await import('node:fs/promises');
	await writeFile(to, banner(label) + (await readFile(from, 'utf8')));
	count += 1;
}

for (const name of components) {
	await vendorSvelte(
		join(headlessSrc, name, `${name}.svelte`),
		join(componentsOut, `${name}.svelte`),
		`lily-design-system-svelte-headless/components/${name}/${name}.svelte`
	);
}

for (const [pkg, name] of helpers) {
	await vendorSvelte(
		join(helpersSrc, pkg, `${name}.svelte`),
		join(helpersOut, `${name}.svelte`),
		`lily-design-system-svelte-helpers/${pkg}/${name}.svelte`
	);
}

for (const theme of themes) {
	const from = join(themesSrc, `${theme}.css`);
	if (!existsSync(from)) {
		missing.push(`themes/${theme}.css`);
		continue;
	}
	await copyFile(from, join(themesOut, `${theme}.css`));
	count += 1;
}

// Barrel files, so pages import from one place: `import { Header } from '$lib/lily'`.
await writeFile(
	join(componentsOut, 'index.js'),
	'// Generated by bin/vendor-lily.mjs. Do not edit.\n' +
		components
			.filter((name) => existsSync(join(componentsOut, `${name}.svelte`)))
			.map((name) => `export { default as ${name} } from './${name}.svelte';`)
			.join('\n') +
		'\n'
);
await writeFile(
	join(helpersOut, 'index.js'),
	'// Generated by bin/vendor-lily.mjs. Do not edit.\n' +
		helpers
			.filter(([, name]) => existsSync(join(helpersOut, `${name}.svelte`)))
			.map(([, name]) => `export { default as ${name} } from './${name}.svelte';`)
			.join('\n') +
		'\n'
);

// The theme list the picker renders, kept in sync with what was actually copied.
await writeFile(
	join(siteRoot, 'src', 'lib', 'themes.js'),
	'// Generated by bin/vendor-lily.mjs. Do not edit.\n' +
		'// The themes vendored into static/assets/themes/, offered by the theme picker.\n' +
		`export const themes = ${JSON.stringify(
			themes.filter((theme) => existsSync(join(themesOut, `${theme}.css`))),
			null,
			'\t'
		)};\n`
);

if (missing.length) console.warn(`skip (missing): ${missing.join(', ')}`);
console.log(`Vendored ${count} Lily files from ${lily}.`);
